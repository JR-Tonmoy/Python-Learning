from math import sqrt, floor, ceil
print(max(40,20))   #সবচেয়ে বড় সংখ্যা বের করা
print(min(40,20))   #সবচেয়ে ছোট সংখ্যা বের করা
print(abs(-40))    #Negative সংখ্যাকে Positive করা
print(pow(2,3))    # Power বা ঘাত বের করা 2*2*2=8print(round(3.5))
print(round(3.5))  #দশমিক সংখ্যাকে Round করা
print(sqrt(15))    #Square Root বের করা
print(floor(3.9))  #নিচের পূর্ণসংখ্যায় নামানো
print(ceil(3.1))   #উপরের পূর্ণসংখ্যায় নেওয়া
